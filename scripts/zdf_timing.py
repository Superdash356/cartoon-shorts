#!/usr/bin/env python3
"""Turn a voice's word timings into zdf/src/timing.js (WORDS, LINES, CAPTIONS, DURATION) for the 3D explainer engine.

usage: python3 scripts/zdf_timing.py shorts/<slug> [duration_seconds] [output, default zdf/src/timing.js]
  reads  shorts/<slug>/lines.json (the script) and words.json (from the "Generate voice" workflow)
  writes zdf/src/timing.js ; duration defaults to the end of the voice + 1.2 s
Captions are 1 to 3 words, broken at punctuation; small words are kept with the word that follows.
"""
import json, re, sys, os
d = sys.argv[1]
w = json.load(open(f"{d}/words.json")); txt = json.load(open(f"{d}/lines.json"))["lines"]
SMALL = {'a','an','the','at','to','of','in','on','and','or','but','for','with','by','it','is','its','as','so','that','if','you','your','be','i','this','up','he','she','just','can'}
lines = {}
for x in w: lines.setdefault(x["line"], []).append(x)
caps = []
for li, ws in lines.items():
    toks = txt[li]["text"].split()
    if len(toks) != len(ws): toks = [x["word"] for x in ws]   # word split differs from the script: fall back to spoken words
    cur = []
    for i, (x, tk) in enumerate(zip(ws, toks)):
        cur.append((x, tk)); t = " ".join(c[1] for c in cur)
        stop = re.search(r"[.,?!;:]$", tk)
        dang = x["word"].lower() in SMALL and i + 1 < len(ws) and len(cur) < 4
        if stop or ((len(cur) >= 3 or len(t) >= 16) and not dang):
            caps.append((cur[0][0]["start"], re.sub(r"[.,;:]+$", "", t), cur[-1][0]["end"])); cur = []
    if cur: caps.append((cur[0][0]["start"], re.sub(r"[.,;:]+$", "", " ".join(c[1] for c in cur)), cur[-1][0]["end"]))
# a caption stays until the next one starts (no overlap, no flicker)
out_caps = []
for i, (s, t, e) in enumerate(caps):
    end = min(e + 0.25, caps[i + 1][0] - 0.03) if i + 1 < len(caps) else e + 0.3
    out_caps.append((max(0, s - 0.03), t, max(end, s + 0.1)))
dur = float(sys.argv[2]) if len(sys.argv) > 2 and sys.argv[2] != "auto" else round(w[-1]["end"] + 1.2, 2)
o = "// generated by scripts/zdf_timing.py from the voice word timings - do not edit by hand\n"
o += f"export const DURATION = {dur};\n"
o += "export const WORDS = " + json.dumps([[x["line"], x["word"], x["start"], x["end"]] for x in w]) + ";\n"
o += "export const LINES = " + json.dumps([[ws[0]["start"], ws[-1]["end"]] for ws in lines.values()]) + ";\n"
o += "export const CAPTIONS = [\n" + "".join(f"  [{s:.2f}, {json.dumps(t)}, {e:.2f}],\n" for s, t, e in out_caps) + "];\n"
root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
out = sys.argv[3] if len(sys.argv) > 3 else f"{root}/zdf/src/timing.js"
open(out, "w").write(o)
print("captions", len(out_caps), "duration", dur)
